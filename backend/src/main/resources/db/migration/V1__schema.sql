-- USD amounts: numeric(12,2). Crypto amounts: numeric(30,12) (2 decimals would be useless for BTC).

CREATE TABLE users (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email          varchar(254) NOT NULL,
    password_hash  varchar(100) NOT NULL,
    display_name   varchar(50)  NOT NULL,
    role           varchar(10)  NOT NULL DEFAULT 'USER',
    balance        numeric(12,2) NOT NULL DEFAULT 0,
    failed_logins  integer      NOT NULL DEFAULT 0,
    locked_until   timestamptz,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT users_role_chk CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT users_balance_nonneg CHECK (balance >= 0)
);
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));

CREATE TABLE refresh_tokens (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   char(64)    NOT NULL,
    family_id    uuid        NOT NULL,
    expires_at   timestamptz NOT NULL,
    revoked_at   timestamptz,
    replaced_by  uuid,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX refresh_tokens_hash_uq ON refresh_tokens (token_hash);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family_id);

CREATE TABLE categories (
    id          varchar(40) PRIMARY KEY,
    label       varchar(80) NOT NULL,
    icon        varchar(40),
    image       varchar(255),
    sort_order  integer     NOT NULL DEFAULT 0
);

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  varchar(40)   NOT NULL REFERENCES categories (id),
    name         varchar(160)  NOT NULL,
    description  varchar(500),
    price        numeric(12,2) NOT NULL,
    image        varchar(255),
    image_fit    varchar(10)   NOT NULL DEFAULT 'cover',
    stock        integer       NOT NULL DEFAULT 0,
    badge        varchar(30),
    active       boolean       NOT NULL DEFAULT true,
    created_at   timestamptz   NOT NULL DEFAULT now(),
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT products_price_pos CHECK (price > 0),
    CONSTRAINT products_stock_nonneg CHECK (stock >= 0),
    CONSTRAINT products_image_fit_chk CHECK (image_fit IN ('cover', 'contain'))
);
CREATE INDEX products_category_idx ON products (category_id);

CREATE TABLE cart_items (
    user_id     uuid    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id  bigint  NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    qty         integer NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id),
    CONSTRAINT cart_items_qty_chk CHECK (qty BETWEEN 1 AND 99)
);

CREATE TABLE orders (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    reference   varchar(24)   NOT NULL,
    user_id     uuid          NOT NULL REFERENCES users (id),
    total       numeric(12,2) NOT NULL,
    status      varchar(12)   NOT NULL DEFAULT 'COMPLETED',
    created_at  timestamptz   NOT NULL DEFAULT now(),
    updated_at  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT orders_total_nonneg CHECK (total >= 0),
    CONSTRAINT orders_status_chk CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED'))
);
CREATE UNIQUE INDEX orders_reference_uq ON orders (reference);
CREATE INDEX orders_user_idx ON orders (user_id, created_at DESC);

CREATE TABLE order_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    uuid          NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id  bigint        REFERENCES products (id) ON DELETE SET NULL,
    name        varchar(160)  NOT NULL,   -- snapshot at purchase time
    unit_price  numeric(12,2) NOT NULL,   -- snapshot at purchase time
    qty         integer       NOT NULL,
    CONSTRAINT order_items_qty_chk CHECK (qty BETWEEN 1 AND 99),
    CONSTRAINT order_items_price_nonneg CHECK (unit_price >= 0)
);
CREATE INDEX order_items_order_idx ON order_items (order_id);

CREATE TABLE payment_methods (
    id                    varchar(20) PRIMARY KEY,   -- matches PAY_OPTIONS ids in the frontend
    symbol                varchar(10)  NOT NULL,
    name                  varchar(40)  NOT NULL,
    network               varchar(60)  NOT NULL,
    coingecko_id          varchar(40)  NOT NULL,
    confirmations         integer      NOT NULL DEFAULT 3,
    stable                boolean      NOT NULL DEFAULT false,
    wallet_address        varchar(200),              -- set by admin; NULL = method unusable
    explorer_tx_url       varchar(255),              -- {tx} is replaced by the tx hash
    requires_tx_key       boolean      NOT NULL DEFAULT false,
    accepted              boolean      NOT NULL DEFAULT true,
    sort_order            integer      NOT NULL DEFAULT 0,
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT payment_methods_conf_chk CHECK (confirmations >= 0)
);

CREATE TABLE deposits (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    reference         varchar(24)   NOT NULL,
    user_id           uuid          NOT NULL REFERENCES users (id),
    method_id         varchar(20)   NOT NULL REFERENCES payment_methods (id),
    usd_amount        numeric(12,2) NOT NULL,
    locked_rate       numeric(30,12) NOT NULL,
    expected_crypto   numeric(30,12) NOT NULL,
    wallet_address    varchar(200)  NOT NULL,     -- copied at creation, never changes
    expires_at        timestamptz   NOT NULL,
    status            varchar(24)   NOT NULL DEFAULT 'AWAITING_PAYMENT',
    tx_hash           varchar(200),
    tx_key            varchar(200),               -- XMR only
    proof_path        varchar(255),
    rejection_reason  varchar(500),
    submitted_at      timestamptz,
    reviewed_by       uuid REFERENCES users (id),
    reviewed_at       timestamptz,
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT deposits_amount_chk CHECK (usd_amount BETWEEN 5 AND 10000),
    CONSTRAINT deposits_rate_pos CHECK (locked_rate > 0),
    CONSTRAINT deposits_crypto_pos CHECK (expected_crypto > 0),
    CONSTRAINT deposits_status_chk CHECK (status IN
        ('AWAITING_PAYMENT', 'PENDING_VERIFICATION', 'APPROVED', 'REJECTED', 'EXPIRED'))
);
CREATE UNIQUE INDEX deposits_reference_uq ON deposits (reference);
CREATE INDEX deposits_user_idx ON deposits (user_id, created_at DESC);
CREATE INDEX deposits_status_idx ON deposits (status, submitted_at);
-- The same on-chain transaction can never back two live deposits.
CREATE UNIQUE INDEX deposits_txhash_live_uq ON deposits (lower(tx_hash))
    WHERE tx_hash IS NOT NULL AND status IN ('PENDING_VERIFICATION', 'APPROVED');

CREATE TABLE balance_ledger (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        uuid          NOT NULL REFERENCES users (id),
    type           varchar(12)   NOT NULL,
    amount         numeric(12,2) NOT NULL,        -- signed: + credit, - debit
    balance_after  numeric(12,2) NOT NULL,
    ref_type       varchar(20),
    ref_id         uuid,
    note           varchar(255),
    created_at     timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ledger_type_chk CHECK (type IN ('DEPOSIT', 'PURCHASE', 'ADJUSTMENT')),
    CONSTRAINT ledger_amount_nonzero CHECK (amount <> 0),
    CONSTRAINT ledger_balance_nonneg CHECK (balance_after >= 0)
);
CREATE INDEX ledger_user_idx ON balance_ledger (user_id, created_at DESC);
-- A deposit can be credited once, an order charged once: enforced by the database.
CREATE UNIQUE INDEX ledger_once_per_ref_uq ON balance_ledger (type, ref_id)
    WHERE type IN ('DEPOSIT', 'PURCHASE') AND ref_id IS NOT NULL;

CREATE TABLE audit_log (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     uuid REFERENCES users (id) ON DELETE SET NULL,
    action       varchar(60) NOT NULL,
    target_type  varchar(30),
    target_id    varchar(64),
    details      jsonb,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_created_idx ON audit_log (created_at DESC);
